export const IMPORT_PROMPT = `我要把一个「月经记录」App 里的历史数据迁移到另一个 App。请你把我接下来发给你的内容（截图、导出的文本或文件）整理成下面这种 JSON，然后直接输出 JSON 本身。

【只提取两种事件】
- "start"：一次月经的第一天
- "end"：同一次月经的最后一天
流量、症状、体温、心情、备注、排卵试纸、体重等其它信息一律不要；中间的日期也不用记。

【输出结构】原样照抄这个外壳：
{
  "format": "moon.period-log",
  "version": 1,
  "exportedAt": "2026-09-28T10:12:00+08:00",
  "events": [
    { "date": "2026-08-29", "type": "start" },
    { "date": "2026-09-02", "type": "end" }
  ]
}

【硬性规则】
1. date 必须是本地日历日期，格式 YYYY-MM-DD（月和日补零），不要带时间、不要带时区。
2. events 按 date 升序排列。
3. start 和 end 必须严格交替：一个 start 紧跟一个 end，再一个 start，再一个 end。某个 end 的日期不能早于它前面那个 start。
4. 只写已经发生的日期，绝对不要写未来的日期。
5. 看不清、被裁掉、或者拿不准的日期就不要写。不要猜测、不要推算、不要补齐。
6. 如果一次月经只看到了第一天、看不到最后一天，就把最后一天记为「第一天 + 4 天」（即一次月经按 5 天算）。这样做只是为了让格式合法，不会影响周期长度的计算。
7. 如果内容里只有某次月经的最后一天而看不到第一天，跳过它，不要为它编一个 start。
8. 日期如果只写了「月/日」而没有年份，按离截图时间最近的那一年推断；推断不出年份的整条跳过。

【输出要求】
- 只输出这个 JSON。不要写解释、不要加标题、不要用 Markdown 代码块包围、前后不要有任何别的文字。
- 如果内容里完全找不到可辨认的月经日期，只回复一个词：NO_DATA

准备好了先回复「好」，我会把内容发给你。`;